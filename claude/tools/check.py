#!/usr/bin/env python3
"""Regenerate claude/INDEX.md from frontmatter and check the dotfiles for drift.

usage: check.py            write INDEX.md, report problems (exit 1 if any)
       check.py --check    do not write; also report a stale INDEX.md
"""
import json, re, sys
from pathlib import Path

CLAUDE = Path(__file__).resolve().parents[1]
ROOT = CLAUDE.parent
INDEX = CLAUDE / "INDEX.md"
problems = []


def frontmatter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    fields = {}
    for line in m.group(1).splitlines():
        k, sep, v = line.partition(":")
        if sep and not line.startswith((" ", "\t")):
            fields[k.strip()] = v.strip().strip('"')
    return fields


def first_sentence(s, limit=220):
    s = re.split(r"(?<=[.!?])\s", s, maxsplit=1)[0]
    return s if len(s) <= limit else s[: limit - 1] + "…"


def rel(p):
    return p.relative_to(CLAUDE).as_posix()


rows = {"Skills": [], "Agents": [], "Commands": [], "Hooks": []}

for d in sorted(p for p in (CLAUDE / "skills").iterdir() if p.is_dir()):
    f = d / "SKILL.md"
    if not f.exists():
        problems.append(f"skill without SKILL.md: {rel(d)}")
        continue
    fm = frontmatter(f)
    if fm.get("name") != d.name:
        problems.append(f"{rel(f)}: name {fm.get('name')!r} differs from directory")
    if not fm.get("description"):
        problems.append(f"{rel(f)}: no description")
    rows["Skills"].append((d.name, fm.get("description", ""), rel(f)))

seen = {}
for f in sorted((CLAUDE / "agents").rglob("*.md")):
    fm = frontmatter(f)
    name = fm.get("name") or f.stem
    if f.stem != name:
        problems.append(f"{rel(f)}: name {name!r} differs from file name")
    if name in seen:
        problems.append(f"agent name {name!r} used twice ({seen[name]}, {rel(f)}); install.sh flattens agents")
    seen[name] = rel(f)
    for key in ("description", "tools"):
        if not fm.get(key):
            problems.append(f"{rel(f)}: no {key}")
    rows["Agents"].append((name, fm.get("description", ""), rel(f)))

for f in sorted((CLAUDE / "commands").rglob("*.md")):
    parts = f.relative_to(CLAUDE / "commands").with_suffix("").parts
    name = "/" + ":".join(parts)
    fm = frontmatter(f)
    if not fm.get("description"):
        problems.append(f"{rel(f)}: no description")
    rows["Commands"].append((name, fm.get("description", ""), rel(f)))

for f in sorted((CLAUDE / "hooks").rglob("*")):
    if f.suffix not in (".sh", ".py"):
        continue
    lines = f.read_text(encoding="utf-8").splitlines()[1:6]
    desc = " ".join(l.lstrip("# ").strip() for l in lines if l.startswith("#"))
    rows["Hooks"].append((f.name, desc, rel(f)))

try:
    settings = json.loads((CLAUDE / "settings.json").read_text())
except json.JSONDecodeError as e:
    problems.append(f"settings.json is not valid JSON: {e}")
    settings = {}
for event in settings.get("hooks", {}).values():
    for group in event:
        for h in group.get("hooks", []):
            for m in re.findall(r"\$HOME\"?(/[^\s\"']+)", h.get("command", "")):
                if not (Path.home() / m.lstrip("/")).exists():
                    problems.append(f"settings.json hook points at a missing file: ~{m}")

for f in list(CLAUDE.rglob("*.md")) + [ROOT / "AGENTS.md", ROOT / "README.md"]:
    if f == INDEX or not f.exists():
        continue
    for m in re.findall(r"~/Git/dotfiles/[^\s`'\")\]|,;]+", f.read_text(encoding="utf-8")):
        path = re.split(r"[*{<]", m.rstrip(".:"), maxsplit=1)[0]
        if not (Path.home() / path[2:]).exists():
            problems.append(f"{f.relative_to(ROOT)}: dangling path {m}")

out = ["# Index", "", "Generated by `claude/tools/check.py` from the frontmatter of each file; do not edit by hand.", ""]
for section, items in rows.items():
    out += [f"## {section}", "", "| Name | What it does | File |", "|---|---|---|"]
    out += [f"| `{n}` | {first_sentence(d).replace('|', '/')} | `{p}` |" for n, d, p in items]
    out.append("")
text = "\n".join(out)

if "--check" in sys.argv:
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != text:
        problems.append("INDEX.md is stale: run claude/tools/check.py")
else:
    INDEX.write_text(text, encoding="utf-8")

for p in problems:
    print("PROBLEM:", p)
print(f"{sum(len(v) for v in rows.values())} items indexed, {len(problems)} problems")
sys.exit(1 if problems else 0)
